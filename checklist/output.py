def to_html(checklist: ComplianceChecklist) -> str:
    """Render a compliance checklist as a standalone HTML page."""
    s = checklist.summary
    categorized = checklist.categorized_items()

    category_labels = {
        "aml": "🔒 AML / BSA Compliance",
        "consumer_protection": "📋 Consumer Protection",
        "privacy": "🔐 Privacy & Data Protection",
        "licensing": "📄 Licensing & Registration",
        "securities": "📈 Securities Compliance",
        "cybersecurity": "🛡️ Cybersecurity",
        "banking": "🏦 Banking / Partnership",
        "other": "📌 Other Requirements",
    }

    categories_html_parts = []

    for cat_slug, items in categorized.items():
        label = category_labels.get(cat_slug, cat_slug.title())
        items_html = []
        for item in items:
            priority_class = "priority-critical" if item.priority <= 2 else "priority-high" if item.priority <= 4 else "priority-medium"
            effort_badge = {"low": "✅ Low", "medium": "🔧 Medium", "high": "🏗️ High"}.get(item.estimated_effort, item.estimated_effort)
            section_html = f' <span class="section">{item.section}</span>' if item.section else ""
            description_html = f'<p class="description">{item.description}</p>' if item.description else ""

            actions_html = ""
            if item.action_items:
                items_list = "\n".join(f"<li>{a.replace('🚨 ', '').replace('🚨', '')}</li>" for a in item.action_items)
                actions_html = f'<ol class="actions">{items_list}</ol>'

            resources_html = ""
            if item.resources:
                res_links = "\n".join(f'<li><a href="{r["url"]}" target="_blank">{r["title"]}</a></li>' for r in item.resources)
                resources_html = f'<div class="resources"><strong>Resources:</strong><ul>{res_links}</ul></div>'

            items_html.append(f"""\
    <div class="item {priority_class}">
      <h3>{item.title}{section_html}</h3>
      <div class="tags">
        <span class="tag">Priority: {item.priority}/10</span>
        <span class="tag">{effort_badge}</span>
      </div>
      {description_html}
      {actions_html}
      {resources_html}
    </div>""")

        categories_html_parts.append(f"""\
  <div class="category">
    <h2>{label}</h2>
    {''.join(items_html)}
  </div>""")

    return HTML_TEMPLATE.format(
        display_name=checklist.display_name,
        generated_at=checklist.generated_at,
        jurisdiction=checklist.jurisdiction,
        total=s["total_items"],
        critical=s["critical"],
        high=s["high_priority"],
        categories_html="\n".join(categories_html_parts),
    )


