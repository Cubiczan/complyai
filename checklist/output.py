# ─── Markdown Output ─────────────────────────────────────────────────────────


def to_markdown(checklist: ComplianceChecklist) -> str:
    """Render a compliance checklist as Markdown."""
    lines = []
    s = checklist.summary

    lines.append(f"# Compliance Checklist: {checklist.display_name}")
    lines.append(f"")
    lines.append(f"**Generated:** {checklist.generated_at}")
    lines.append(f"**Jurisdiction:** {checklist.jurisdiction}")
    lines.append(f"")
    lines.append(f"## Summary")
    lines.append(f"")
    lines.append(f"- **{s['total_items']}** total requirements")
    lines.append(f"- **{s['critical']}** critical (must-do immediately)")
    lines.append(f"- **{s['high_priority']}** high priority (do within 90 days)")
    lines.append(f"- Categories: {', '.join(s['categories'])}")
    lines.append(f"")

    # Group by category
    categorized = checklist.categorized_items()
    category_labels = {
        "aml": "🔒 AML / BSA Compliance",
        "consumer_protection": "📋 Consumer Protection",
        "privacy": "🔐 Privacy & Data Protection",
        "licensing": "📄 Licensing & Registration",
        "securities": "📈 Securities Compliance",
        "cybersecurity": "🛡️ Cybersecurity",
        "banking": "🏦 Banking / Partnership",
        "other": "📌 Other Requirements",
    }

    for category_slug, items in categorized.items():
        label = category_labels.get(category_slug, category_slug.title())
        lines.append(f"## {label}")
        lines.append(f"")

        for item in items:
            emoji = "🔴" if item.priority <= 2 else "🟡" if item.priority <= 4 else "🟢"
            effort_badge = {
                "low": "✅ Low effort",
                "medium": "🔧 Medium effort",
                "high": "🏗️ High effort",
            }.get(item.estimated_effort, item.estimated_effort)

            lines.append(f"### {emoji} {item.title}")
            if item.section:
                lines.append(f"**Section:** `{item.section}`")
            lines.append(f"**Priority:** {item.priority}/10 | **Effort:** {effort_badge}")
            if item.description:
                lines.append(f"")
                lines.append(f"{item.description}")
            lines.append(f"")
            lines.append(f"**Action items:**")
            for action in item.action_items:
                lines.append(f"- [ ] {action}")
            lines.append(f"")
            if item.resources:
                lines.append(f"**Resources:**")
                for res in item.resources:
                    lines.append(f"- [{res['title']}]({res['url']})")
            lines.append(f"")

    lines.append("---")
    lines.append(f"*This checklist was generated by complyAI and is for informational purposes only. It does not constitute legal advice. Consult with a qualified attorney for your specific situation.*")

    return "\n".join(lines)


